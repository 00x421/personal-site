const WINTER_SOLSTICE = { name: '冬至', gloss: '一阳生，日短之至' } as const;

/** 当天所处的节气：年初未到小寒时落在去年的冬至里。 */
export function currentSolarTerm(now: Date): { name: string; gloss: string } {
  const month = now.getMonth() + 1;
  const day = now.getDate();
  let found: { name: string; gloss: string } = WINTER_SOLSTICE;
  for (const [m, d, name, gloss] of TERMS) {
    if (month > m || (month === m && day >= d)) found = { name, gloss };
  }
  return found;
}
